class FakeEmbedService(RoutedModelService):
    """A real RoutedModelService whose embedding provider is scripted."""

    def __init__(self) -> None:
        from app.llm import EmbeddingProvider

        outer = self

        class _Provider(EmbeddingProvider):
            name = "fake-embed"

            def embed(self, request):
                outer.seen.extend(request.texts)
                return EmbeddingResponse(
                    vectors=[[0.25] * DIMS for _ in request.texts],
                    served_model=request.model,
                    input_tokens=7,
                )

        self.seen: list[str] = []
        self.rows: list = []
        super().__init__(
            provider=AnthropicProvider(client=None),
            recorder=self.rows.append,
            embedding_provider=_Provider(),
        )


def seed_snapshot(conn: psycopg.Connection, repo_id: str, sha: str) -> None:
    """One file node, one symbol node, one blob -- what the scan pass leaves."""
    source = "import os\n\n\ndef greet(name):\n    return f'hi {name}'\n"
    insert_nodes(
        conn,
        [
            Node(
                repo_id=repo_id,
                commit_sha=sha,
                kind="file",
                name="greet.py",
                path="greet.py",
                attrs={"language": "python", "tier": "full"},
                analyzer="tree-sitter",
                analyzer_version="0.1.0",
                status="verified",
            ),
            Node(
                repo_id=repo_id,
                commit_sha=sha,
                kind="symbol",
                name="greet",
                path="greet.py",
                line_start=4,
                line_end=5,
                analyzer="tree-sitter",
                analyzer_version="0.1.0",
                status="verified",
            ),
        ],
    )
    upsert_blobs(
        conn,
        [
            Blob(
                repo_id=repo_id,
                commit_sha=sha,
                path="greet.py",
                content=source,
                content_hash="hash-of-greet",
            )
        ],
    )


def coverage_row(conn, repo_id, sha, metric):
    rows = [r for r in list_coverage(conn, repo_id, sha) if r.metric == metric]
    assert len(rows) == 1, f"expected exactly one {metric} coverage row, got {len(rows)}"
    return rows[0]


def test_chunk_pass_without_an_embedding_provider_still_chunks_and_searches(repo_id):
    # Requirement 6: with no VOYAGE_API_KEY the pass must complete, chunks are
    # stored with embedding = NULL, FTS works, and the gap is recorded.
    sha = f"test-{uuid.uuid4().hex[:12]}"
    assert not os.environ.get("VOYAGE_API_KEY")  # the conftest guard
    with worker_connection() as conn:
        seed_snapshot(conn, repo_id, sha)
        write_chunk_pass(conn, repo_id, sha)

        chunks = list_chunks(conn, repo_id, sha)
        assert chunks, "the pass produced no chunks"
        assert all(c.embedding is None and c.embedding_model is None for c in chunks)
        assert {c.path for c in chunks} == {"greet.py"}
        assert any(c.symbol == "greet" for c in chunks)
        assert search_chunks_fts(conn, repo_id, sha, "greet")

        embedded = coverage_row(conn, repo_id, sha, "chunks_embedded")
        assert embedded.resolved == 0 and embedded.total == len(chunks)
        assert embedded.blockers == {"embedding_not_configured": len(chunks)}
        assert coverage_row(conn, repo_id, sha, "files_chunked").total == 1

        runs = [r for r in list_pass_runs(conn, repo_id) if r.analyzer == ANALYZER]
        assert [r.status for r in runs] == [PassRunStatus.SUCCEEDED]


def test_chunk_pass_with_a_provider_embeds_then_reuses_on_the_next_commit(repo_id):
    sha_one = f"test-{uuid.uuid4().hex[:12]}"
    sha_two = f"test-{uuid.uuid4().hex[:12]}"
    service = FakeEmbedService()

    with worker_connection() as conn:
        seed_snapshot(conn, repo_id, sha_one)
        write_chunk_pass(conn, repo_id, sha_one, service=service)

        chunks = list_chunks(conn, repo_id, sha_one)
        assert chunks and all(c.embedding is not None for c in chunks)
        assert all(len(c.embedding or []) == DIMS for c in chunks)
        assert all(c.embedding_model == "voyage-code-3" for c in chunks)
        embedded = coverage_row(conn, repo_id, sha_one, "chunks_embedded")
        assert (embedded.resolved, embedded.total) == (len(chunks), len(chunks))
        assert embedded.blockers == {}
        # One usage row per provider request, written by ModelService.
        assert [r.role for r in service.rows] == ["embed"]
        assert service.rows[0].operation == "embed"
        first_call_count = len(service.seen)
        assert first_call_count == len(chunks)

        # Same content at a new commit: the vectors are reused, so the
        # provider sees nothing new (build-plan.md Part 4.D).
        seed_snapshot(conn, repo_id, sha_two)
        write_chunk_pass(conn, repo_id, sha_two, service=service)

        assert len(service.seen) == first_call_count, "re-embedded unchanged content"
        reused = coverage_row(conn, repo_id, sha_two, "chunk_embeddings_reused")
        assert reused.resolved == len(chunks)
        assert all(c.embedding is not None for c in list_chunks(conn, repo_id, sha_two))


def test_chunk_pass_records_an_embedding_failure_without_losing_the_chunks(repo_id):
    sha = f"test-{uuid.uuid4().hex[:12]}"

    from app.llm import EmbeddingProvider

    class Broken(EmbeddingProvider):
        name = "broken"

        def embed(self, request):
            raise ConnectionError("voyage unreachable")

    rows: list = []
    service = RoutedModelService(
        provider=AnthropicProvider(client=None),
        recorder=rows.append,
        embedding_provider=Broken(),
    )

    with worker_connection() as conn:
        seed_snapshot(conn, repo_id, sha)
        write_chunk_pass(conn, repo_id, sha, service=service)

        chunks = list_chunks(conn, repo_id, sha)
        assert chunks, "a failed embedding must not discard the chunks"
        assert all(c.embedding is None for c in chunks)
        blockers = coverage_row(conn, repo_id, sha, "chunks_embedded").blockers
        assert blockers == {"embedding_failed": len(chunks)}
        # The failed provider attempt is still recorded as a model call.
        assert [r.status for r in rows] == ["error"]
        runs = [r for r in list_pass_runs(conn, repo_id) if r.analyzer == ANALYZER]
        assert [r.status for r in runs] == [PassRunStatus.SUCCEEDED]



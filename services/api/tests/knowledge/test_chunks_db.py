def test_vector_round_trip_and_reuse_lookup(repo_id):
    sha = f"test-{uuid.uuid4().hex[:12]}"
    vector = [round(i / DIMS, 6) for i in range(DIMS)]
    with worker_connection() as conn:
        (chunk_id,) = insert_chunks(conn, [chunk(repo_id, sha)])
        assert (
            set_chunk_embeddings(
                conn, [(chunk_id, vector)], embedding_model="voyage-code-3"
            )
            == 1
        )

        stored = get_chunk(conn, chunk_id)
        assert stored is not None
        assert stored.embedding is not None and len(stored.embedding) == DIMS
        assert stored.embedding[:4] == pytest.approx(vector[:4], abs=1e-6)
        assert stored.embedding_model == "voyage-code-3"
        assert stored.embedded_at is not None
        assert count_chunks(conn, repo_id, sha) == (1, 1)

        # The incremental re-index key: same repo, same content, new commit.
        hashes = [content_hash("def main():\n    return 1")]
        found = find_reusable_embeddings(conn, repo_id, hashes)
        assert set(found) == set(hashes)
        reused_vector, reused_model = found[hashes[0]]
        assert len(reused_vector) == DIMS and reused_model == "voyage-code-3"
        assert find_reusable_embeddings(conn, repo_id, []) == {}
        assert find_reusable_embeddings(conn, repo_id, ["nope"]) == {}


def test_reuse_lookup_never_crosses_repositories(repo_id, db_project):
    sha = f"test-{uuid.uuid4().hex[:12]}"
    with worker_connection() as conn:
        other = create_repo(conn, Repo(project_id=db_project, remote_url="https://e.com/o.git"))
        assert other.id is not None
        (chunk_id,) = insert_chunks(conn, [chunk(repo_id, sha)])
        set_chunk_embeddings(conn, [(chunk_id, [0.1] * DIMS)], embedding_model="voyage-code-3")
        same_content = [content_hash("def main():\n    return 1")]
        assert find_reusable_embeddings(conn, other.id, same_content) == {}



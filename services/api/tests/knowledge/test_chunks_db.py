def test_insert_read_back_and_fts(repo_id):
    sha = f"test-{uuid.uuid4().hex[:12]}"
    with worker_connection() as conn:
        ids = insert_chunks(
            conn,
            [
                chunk(repo_id, sha, path="auth.py", symbol="verify_token"),
                chunk(
                    repo_id,
                    sha,
                    path="util.py",
                    symbol="slugify",
                    content="def slugify(value):\n    return value.lower()",
                ),
            ],
        )
        assert len(ids) == 2

        stored = list_chunks(conn, repo_id, sha)
        assert [c.path for c in stored] == ["auth.py", "util.py"]
        assert [c.symbol for c in stored] == ["verify_token", "slugify"]
        assert all(c.embedding is None and c.embedded_at is None for c in stored)
        assert all((c.analyzer, c.analyzer_version) == (ANALYZER, ANALYZER_VERSION) for c in stored)

        one = get_chunk(conn, ids[0])
        assert one is not None and one.path == "auth.py"
        assert list_chunks(conn, repo_id, sha, path="util.py")[0].symbol == "slugify"

        # `tsv` is generated by Postgres from symbol/path/content -- never
        # written by this code -- so search works the moment a row exists.
        hits = search_chunks_fts(conn, repo_id, sha, "slugify")
        assert [c.path for c, _rank in hits] == ["util.py"]
        assert all(rank > 0 for _c, rank in hits)
        assert search_chunks_fts(conn, repo_id, sha, "nothing-matches-this") == []
        # A query string that is operator syntax must not raise.
        assert search_chunks_fts(conn, repo_id, sha, "slugify & | !") is not None



def chunk(
    repo_id: str,
    commit_sha: str,
    *,
    path: str = "a.py",
    symbol: str | None = "main",
    content: str = "def main():\n    return 1",
    line_start: int = 1,
    line_end: int = 2,
    part_index: int = 0,
    part_count: int = 1,
    node_id: int | None = None,
    embedding: list[float] | None = None,
    embedding_model: str | None = None,
) -> Chunk:
    return Chunk(
        repo_id=repo_id,
        commit_sha=commit_sha,
        node_id=node_id,
        path=path,
        symbol=symbol,
        kind="symbol" if symbol else "module",
        line_start=line_start,
        line_end=line_end,
        content=content,
        content_hash=content_hash(content),
        token_count=len(content) // 4 + 1,
        part_index=part_index,
        part_count=part_count,
        embedding=embedding,
        embedding_model=embedding_model,
        analyzer=ANALYZER,
        analyzer_version=ANALYZER_VERSION,
    )



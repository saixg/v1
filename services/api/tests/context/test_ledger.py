"""Constraint Ledger auto-detection: deterministic, provenance-bearing, and
unconfirmed by default. Pure detection tests plus one live-database round trip
that also proves a re-run never deletes a user-stated constraint."""

from __future__ import annotations

import json
import os
from collections.abc import Iterator

import pytest
from dotenv import load_dotenv

from app.context.ledger import (
    ANALYZER,
    FileFact,
    LedgerSnapshot,
    detect_constraints,
    write_ledger_pass,
)
from app.knowledge import (
    create_project,
    create_repo,
    insert_constraints,
    insert_nodes,
    list_constraints,
    upsert_blobs,
    worker_connection,
)
from app.models import Blob, Constraint, Convention, Node, Repo

load_dotenv()

FILES = [
    "src/app/main.py",
    "src/app/auth/tokens.py",
    "src/app/middleware.py",
    "supabase/migrations/001_init.sql",
    "supabase/migrations/002_more.sql",
    "package-lock.json",
    "web/vendor/lib/x.js",
    "src/gen/schema_pb2.py",
    "src/hand.py",
    "tests/test_auth.py",
]
ROUTES = '@router.get("/health")\ndef health(): ...\n\n@router.post("/chat")\ndef chat(): ...\n'
GENERATED = "# Code generated by tool. DO NOT EDIT.\nX = 1\n"


def snapshot(**over) -> LedgerSnapshot:
    fields: dict = {
        "files": [FileFact(path=p, node_id=i, loc=10) for i, p in enumerate(FILES, start=1)],
        "blobs": {"src/app/main.py": ROUTES, "src/hand.py": GENERATED},
        "conventions": [
            Convention(repo_id="r", commit_sha="c", category="lint", rule="ruff line-length 100",
                       origin="configured", evidence={"source": "pyproject.toml"},
                       analyzer="conv", analyzer_version="1"),
            Convention(repo_id="r", commit_sha="c", category="lint", rule="guessed style",
                       origin="inferred", analyzer="conv", analyzer_version="1"),
            Convention(repo_id="r", commit_sha="c", category="ci", rule="CI runs pytest",
                       origin="configured", evidence={"source": ".github/workflows/ci.yml"},
                       analyzer="conv", analyzer_version="1"),
        ],
    }
    fields.update(over)
    return LedgerSnapshot(**fields)


def by_kind(rows: list[Constraint], kind: str) -> dict[str, Constraint]:
    return {r.scope: r for r in rows if r.kind == kind}


def test_every_row_is_an_unconfirmed_auto_detection_with_provenance() -> None:
    rows = detect_constraints("r", "c", snapshot())
    assert rows
    for r in rows:
        assert r.source == "auto_detected" and r.confirmed is False
        assert r.analyzer == ANALYZER and r.analyzer_version
        assert r.origin in ("parsed", "configured")  # never a model tag
        assert r.evidence.spans or r.evidence.node_ids or r.evidence.notes


def test_public_api_routes_are_read_literally_with_line_spans() -> None:
    api = by_kind(detect_constraints("r", "c", snapshot()), "public_api")
    row = api["src/app/main.py"]
    assert "GET /health" in row.statement and "POST /chat" in row.statement
    assert [s.line_start for s in row.evidence.spans] == [1, 4]


def test_db_schema_and_auth_boundaries() -> None:
    rows = detect_constraints("r", "c", snapshot())
    assert "supabase/migrations/" in by_kind(rows, "db_schema")
    auth = by_kind(rows, "auth_boundary")
    assert "src/app/auth/" in auth and "src/app/middleware.py" in auth
    # Test files are not auth boundaries.
    assert "tests/test_auth.py" not in auth


def test_ci_lint_promotes_only_configured_conventions() -> None:
    ci = by_kind(detect_constraints("r", "c", snapshot()), "ci_lint")
    assert set(ci) == {"pyproject.toml", ".github/workflows/ci.yml"}
    assert ci[".github/workflows/ci.yml"].severity == "hard"
    assert all(r.origin == "configured" for r in ci.values())


def test_do_not_touch_covers_lock_vendored_generated_and_existing_migrations() -> None:
    dnt = by_kind(detect_constraints("r", "c", snapshot()), "do_not_touch")
    assert "package-lock.json" in dnt
    assert "web/vendor/" in dnt
    assert "src/gen/schema_pb2.py" in dnt  # by file name
    assert "src/hand.py" in dnt  # by generator header
    mig = dnt["supabase/migrations/"]
    assert {s.path for s in mig.evidence.spans} == {
        "supabase/migrations/001_init.sql", "supabase/migrations/002_more.sql",
    }


def test_gitattributes_and_package_json_are_configured_facts() -> None:
    snap = snapshot(blobs={
        ".gitattributes": "docs/api/** linguist-generated=true\n*.txt text\n",
        "package.json": json.dumps({"name": "pkg", "main": "dist/index.js"}),
    })
    rows = detect_constraints("r", "c", snap)
    assert by_kind(rows, "do_not_touch")["docs/api/**"].origin == "configured"
    assert by_kind(rows, "public_api")["repo"].origin == "configured"


def test_malformed_manifest_is_a_gap_not_a_guess() -> None:
    rows = detect_constraints("r", "c", snapshot(blobs={"package.json": "{not json"}))
    assert by_kind(rows, "public_api") == {}


def test_detection_is_deterministic() -> None:
    a = [r.model_dump() for r in detect_constraints("r", "c", snapshot())]
    b = [r.model_dump() for r in detect_constraints("r", "c", snapshot())]
    assert a == b


needs_db = pytest.mark.skipif(
    not os.environ.get("WORKER_DATABASE_URL"), reason="WORKER_DATABASE_URL not set"
)


@pytest.fixture
def repo(make_user) -> Iterator[tuple[str, str, str]]:
    user = make_user()
    with worker_connection() as conn:
        project = create_project(conn, "ledger test", user)
        created = create_repo(
            conn, Repo(project_id=project.id, remote_url="https://example.com/octo/led.git")
        )
    assert created.id is not None
    yield created.id, "test-ledger-sha", user


@needs_db
def test_write_ledger_pass_round_trip_keeps_user_stated_rows(repo) -> None:
    repo_id, sha, _ = repo
    with worker_connection() as conn:
        insert_nodes(conn, [
            Node(repo_id=repo_id, commit_sha=sha, kind="file", name=p.rsplit("/", 1)[-1],
                 path=p, analyzer="t", analyzer_version="0", status="verified",
                 attrs={"loc": 10})
            for p in FILES
        ])
        upsert_blobs(conn, [
            Blob(repo_id=repo_id, commit_sha=sha, path="src/app/main.py", content=ROUTES,
                 content_hash="h1"),
            Blob(repo_id=repo_id, commit_sha=sha, path="src/hand.py", content=GENERATED,
                 content_hash="h2"),
        ])
        insert_constraints(conn, [
            Constraint(repo_id=repo_id, commit_sha=sha, kind="other", scope="repo",
                       statement="Never log PII.", severity="hard", source="user_stated",
                       origin="configured"),
        ])
        first = write_ledger_pass(conn, repo_id, sha)
        second = write_ledger_pass(conn, repo_id, sha)  # idempotent re-run
        stored = list_constraints(conn, repo_id, sha)
    detected = [r for r in stored if r.source == "auto_detected"]
    assert len(detected) == len(first) == len(second) > 0
    assert all(r.id for r in first)
    assert {r.scope for r in detected} >= {"src/app/main.py", "package-lock.json"}
    assert [r.statement for r in stored if r.source == "user_stated"] == ["Never log PII."]
